static int16_t log_q8(int idx) {
    if (idx < 0 || idx > 32) return 0;
    return LOG_Q8[idx];
}

static uint16_t golden_y(int aa, int bb, int16_t& es) {
    es = static_cast<int16_t>(log_q8(aa) + log_q8(bb));
    uint8_t ip = static_cast<uint8_t>((es >> 8) & 0xFF);
    uint8_t frac = static_cast<uint8_t>(es & 0xFF);
    uint32_t mant = EXP_MANT[frac];
    uint32_t sh = mant << ip;
    return static_cast<uint16_t>((sh >> 8) & 0xFFFF);
}

int main() {
    Sim<Vlns_mul8> s;
    auto* t = s.top;
    t->in_valid = 0;
    t->a = 1;
    t->b = 1;
    s.reset(3);

    int n = 0;
    for (int ia = 1; ia <= 32; ia++) {
        for (int ib = 1; ib <= 32; ib++) {
            int16_t es;
            uint16_t ey = golden_y(ia, ib, es);
            t->a = ia;
            t->b = ib;
            t->in_valid = 1;
            s.tick();
            if (!t->out_valid || (uint16_t)t->y != ey || s16(t->log_sum) != es)
                fail("lns");
            n++;
            t->in_valid = 0;
            s.tick();
        }
    }
    std::printf("PASS lns_mul8 n=%d mismatches=0\n", n);
    std::printf("METRIC RMSE=0 SNR_dB=999 DOMAIN=1..32\n");
    return 0;
}
